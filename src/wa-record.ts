/** Create an x_wa_message row — or find the one that already carries this wamid (one row per wamid). */
async function createRow(env: Env, vals: Record<string, unknown>): Promise<{ id: number; existed: boolean }> {
  const { call } = await import("./odoo");
  const wamid = typeof vals.x_meta_message_id === "string" ? vals.x_meta_message_id : "";
  if (wamid) {
    const hit = await call<Array<{ id: number }>>(env, "x_wa_message", "search_read", {
      domain: [["x_meta_message_id", "=", wamid]], fields: ["id"], limit: 1,
    });
    if (hit[0]) return { id: hit[0].id, existed: true };
  }
  const ids = await call<number[]>(env, "x_wa_message", "create", { vals_list: [vals] });
  const id = Array.isArray(ids) ? ids[0] : 0;
  if (!id) throw new Error("x_wa_message create returned no id");
  return { id, existed: false };
}

/** The row of a send (throws when Odoo refuses it). Returns its id and whether a line is due. */
async function writeSentRow(env: Env, rec: SentRecord): Promise<{ rowId: number; echo: boolean }> {
  const to = waDigits(rec.to);
  const sentAt = rec.sentAt ?? Date.now();
  const shown = await outboundText(env, rec.body);
  const partner = await partnerForNumber(env, to);
  const echo = !rec.noEcho && !!partner;
  const tech = {
    purpose: rec.purpose,
    ...(shown.templateName ? { template: shown.templateName } : {}),
    ...(shown.kind === "template" && !shown.synced ? { unsynced: true } : {}),
  };
  const vals: Record<string, unknown> = {
    x_status: "sent",
    x_meta_message_id: rec.wamid || false,
    x_processed_at: nowOdoo(sentAt),
    x_echo_status: echo ? "pending" : "none",
    ...(shown.templateId ? { x_template_id: shown.templateId } : {}),
    ...(shown.kind === "template" ? { x_params: JSON.stringify(shown.params ?? []) } : {}),
    ...(partner ? { x_partner_id: partner.id } : {}),
  };
  const { call } = await import("./odoo");
  // § 37 أ — Meta's «delivered» / «read» can arrive before this row carries the
  // wamid (the D1 status log kept it): the row starts at that status, not «sent».
  if (rec.wamid) {
    const { highestLoggedStatus } = await import("./wa-status");
    const hi = await highestLoggedStatus(env, rec.wamid);
    if (hi === "delivered" || hi === "read") vals.x_status = hi;
  }
  if (rec.rowId) {
    if (shown.kind === "template") vals.x_body = shown.text.slice(0, 2000);
    vals.x_source = rec.manual ? "manual" : "auto";
    await call(env, "x_wa_message", "write", { ids: [rec.rowId], vals });
    return { rowId: rec.rowId, echo };
  }
  const r = await createRow(env, {
    ...vals,
    x_direction: "out",
    x_kind: shown.kind,
    x_body: shown.text.slice(0, 2000),
    x_source: rec.manual ? "manual" : "auto",
    x_debug_payload: JSON.stringify(tech).slice(0, 4000),
  });
  // A row that already carried this wamid was written (and shown) by its own path.
  return { rowId: r.id, echo: echo && !r.existed };
}

/**
 * A message Meta accepted: its row (awaited — no message leaves without one),
 * then its Discuss line (in ctx.waitUntil when there is a ctx). A row Odoo
 * refuses is kept in KV for the every-5-minutes retry. Returns the row id.
 */
export async function recordSent(env: Env, rec: SentRecord): Promise<number | undefined> {
  let r: { rowId: number; echo: boolean };
  try {
    r = await writeSentRow(env, rec);
  } catch (e) {
    console.error(`[record] x_wa_message row for purpose=${rec.purpose} to=${maskPhone(rec.to)} failed — kept for the */5 retry`, (e as Error)?.message);
    await keepOrphan(env, { ...rec, sentAt: rec.sentAt ?? Date.now(), ctx: undefined });
    return undefined;
  }
  if (r.echo) await echoRowSoon(env, r.rowId, waDigits(rec.to), rec.ctx);
  return r.rowId;
}

/**
 * A held / expired / skipped / failed / re-held row changed state: its line
 * follows (the held line edited, or a line posted when there is none).
 */
export async function recordStateChange(env: Env, rowId: number | undefined, to: string, ctx?: ExecutionContext): Promise<void> {
  if (!rowId) return;
  try {
    const { call } = await import("./odoo");
    await call(env, "x_wa_message", "write", { ids: [rowId], vals: { x_echo_status: "pending" } });
  } catch (e) {
    console.warn(`[record] row=${rowId} pending mark failed`, (e as Error)?.message);
  }
  await echoRowSoon(env, rowId, waDigits(to), ctx);
}

// ------------------------------------------------------------------ retries (the */5 tick)

export const MAX_ECHO_RETRIES = 3;
export function echoTryKey(rowId: number): string {
  return `wa_echo_try:v1:${rowId}`;
}
const ORPHANS_KEY = "wa_rec:v1:orphans";
interface Orphan { rec: SentRecord; tries: number }

async function keepOrphan(env: Env, rec: SentRecord): Promise<void> {
  try {
    const raw = await env.MSG_DEDUP.get(ORPHANS_KEY);
    const list = (raw ? JSON.parse(raw) : []) as Orphan[];
    list.push({ rec, tries: 0 });
    await env.MSG_DEDUP.put(ORPHANS_KEY, JSON.stringify(list.slice(-200)), { expirationTtl: 3 * 24 * 3600 });
  } catch (e) {
    console.error("[record] orphan not kept (the D1 log still has the send)", (e as Error)?.message);
  }
}

/**
 * Every row whose Discuss line is still «pending» (older than two minutes, so
 * not one being posted right now): one more try each, three at most, then the
 * row is marked «failed». Rows Odoo refused to create are retried the same way.
 */
export async function retryPendingRecords(env: Env, now: number = Date.now()): Promise<{ echoed: number; failed: number; waiting: number; orphans: number }> {
  const out = { echoed: 0, failed: 0, waiting: 0, orphans: 0 };
  // rows Odoo refused to create
  try {
    const raw = await env.MSG_DEDUP.get(ORPHANS_KEY);
    const list = (raw ? JSON.parse(raw) : []) as Orphan[];
    if (list.length) {
      const keep: Orphan[] = [];
      for (const o of list) {
        try {
          const r = await writeSentRow(env, o.rec);
          out.orphans++;
          if (r.echo) await echoRowSoon(env, r.rowId, waDigits(o.rec.to));
        } catch (e) {
          if (o.tries + 1 < MAX_ECHO_RETRIES) keep.push({ rec: o.rec, tries: o.tries + 1 });
          else console.error(`[record] row for purpose=${o.rec.purpose} to=${maskPhone(o.rec.to)} still refused after ${MAX_ECHO_RETRIES} retries — only the D1 log has it`, (e as Error)?.message);
        }
      }
      // a send recorded meanwhile may have added an orphan: keep it too
      const now2 = JSON.parse((await env.MSG_DEDUP.get(ORPHANS_KEY)) ?? "[]") as Orphan[];
      const added = now2.slice(list.length);
      await env.MSG_DEDUP.put(ORPHANS_KEY, JSON.stringify([...keep, ...added]), { expirationTtl: 3 * 24 * 3600 });
    }
  } catch (e) {
    console.warn("[record] orphan retry failed", (e as Error)?.message);
  }
  // rows whose line is pending
  let rows: RowView[] = [];
  try {
    const { call } = await import("./odoo");
    rows = await call<RowView[]>(env, "x_wa_message", "search_read", {
      domain: [["x_echo_status", "=", "pending"], ["write_date", "<=", nowOdoo(now - 2 * 60_000)], ["write_date", ">=", nowOdoo(now - 3 * 24 * 3600_000)]],
      fields: ROW_FIELDS,
      order: "id asc",
      limit: 30,
    });
  } catch (e) {
    console.warn("[record] pending rows unreadable", (e as Error)?.message);
    return out;
  }
  for (const row of rows) {
    const key = echoTryKey(row.id);
    let tries = 0;
    try { tries = Number((await env.MSG_DEDUP.get(key)) ?? "0") || 0; } catch { /* 0 */ }
    try {
      await echoForRow(env, row, await numberOfRow(env, row));
      out.echoed++;
    } catch (e) {
      tries++;
      if (tries >= MAX_ECHO_RETRIES) {
        try {
          await writeRow(env, row.id, { x_echo_status: "failed" });
          out.failed++;
          console.error(`[record] Discuss line row=${row.id} failed ${tries} retries — row marked «failed»`, (e as Error)?.message);
        } catch { out.waiting++; }
      } else {
        out.waiting++;
        try { await env.MSG_DEDUP.put(key, String(tries), { expirationTtl: 3 * 24 * 3600 }); } catch { /* ignore */ }
      }
    }
  }
  return out;
}

async function numberOfRow(env: Env, row: RowView): Promise<string> {
  if (!row.x_partner_id) return "";
  try {
    const { call } = await import("./odoo");
    const [p] = await call<Array<{ x_whatsapp_number: string | false; phone: string | false }>>(env, "res.partner", "read", {
      ids: [row.x_partner_id[0]], fields: ["x_whatsapp_number", "phone"], context: { active_test: false },
    });
    return waDigits(String(p?.x_whatsapp_number || p?.phone || ""));
  } catch {
    return "";
  }
}
