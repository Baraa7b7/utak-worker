// ------------------------------------------------------------------ texts

/** The first characters of every status line (the server action finds the line by them). */
export const STATUS_MARKERS = ["⏳ محفوظة", "✅ أُرسلت", "⌛ انتهت", "⏭️ لم تُرسل", "⚠️ لم تصل"] as const;
export const UNSYNCED_LINE = "⚠️ نص القالب غير متزامن";
export const BACKFILL_TAG = "مستكمل";
export const HELD_LINE_ACTION_NAME = "UTAK — سطر حالة رسالة واتساب";

/** «⏳ محفوظة…» under a held message: what waits, and until when. */
export function heldLine(until: string): string {
  return `⏳ محفوظة: خارج نافذة 24 ساعة ولا قالب معتمد لها. تُرسل تلقائياً عند أول رسالة منه، وتنتهي صلاحيتها ${until}.`;
}

/** Riyadh «HH:MM» of an Odoo UTC datetime ("YYYY-MM-DD HH:MM:SS"), or "". */
export function riyadhHHMM(odooUtc: string | false | null | undefined): string {
  const ms = Date.parse(String(odooUtc || "").replace(" ", "T") + "Z");
  if (!Number.isFinite(ms)) return "";
  const m = riyadhMinutes(new Date(ms));
  return `${String(Math.floor(m / 60)).padStart(2, "0")}:${String(m % 60).padStart(2, "0")}`;
}

/**
 * The status line for a row's x_status — the same function as the server
 * action's Python (heldLineActionCode), checked against it by the setup
 * script. "" = no line for that status.
 */
export function statusLineFor(status: string, at: string, metaError: string): string {
  const err = String(metaError || "").replace("البوابة: ", "").slice(0, 200);
  if (status === "sent" || status === "delivered" || status === "read") return "✅ أُرسلت" + (at ? " " + at : "");
  if (status === "expired") return "⌛ انتهت صلاحيتها ولم تُرسل: لم يراسل الرقم قبلها.";
  if (status === "skipped") return "⏭️ لم تُرسل: " + err;
  if (status === "failed") return "⚠️ لم تصل: " + err;
  if (status === "held") return "⏳ محفوظة من جديد: أغلق Meta النافذة، وتُرسل عند أول رسالة منه.";
  return "";
}

function escapeHtml(s: string): string {
  return String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

/**
 * A body whose last paragraph is a status line, with that line replaced — or
 * null when the last paragraph is not one (the message is left alone). The
 * server action does exactly this (heldLineActionCode).
 */
export function replaceStatusLine(body: string, line: string): string | null {
  const b = String(body ?? "");
  const i = b.lastIndexOf("<p>");
  if (i < 0 || !STATUS_MARKERS.some((m) => b.slice(i + 3).startsWith(m))) return null;
  return b.slice(0, i) + "<p>" + escapeHtml(line) + "</p>";
}

/**
 * The Python of the server action — generated from the functions above so the
 * two never drift (scripts/s36-20260925-odoo.mts writes it and --verify runs
 * its functions in python3 against statusLineFor / replaceStatusLine).
 */
export function heldLineActionCode(): string {
  const py = (s: string) => JSON.stringify(s);
  return `# UTAK § 36 — the status line of a WhatsApp message in its Discuss channel.
# Generated by src/wa-record.ts heldLineActionCode(); do not edit here.
# Run as the x_wa_message row(s): edits only the Discuss message the row
# points to (x_echo_message_id), only when it is a line of «UTAK بوت» in a
# WhatsApp channel, and only its last paragraph when that is a status line.
MARKERS = (${STATUS_MARKERS.map(py).join(", ")})

def status_line(st, at, err):
    err = (err or '').replace(${py("البوابة: ")}, '', 1)[:200]
    if st in ('sent', 'delivered', 'read'):
        return ${py("✅ أُرسلت")} + ((' ' + at) if at else '')
    if st == 'expired':
        return ${py(statusLineFor("expired", "", ""))}
    if st == 'skipped':
        return ${py("⏭️ لم تُرسل: ")} + err
    if st == 'failed':
        return ${py("⚠️ لم تصل: ")} + err
    if st == 'held':
        return ${py(statusLineFor("held", "", ""))}
    return ''

def esc(s):
    return s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')

def new_body(body, line):
    i = body.rfind('<p>')
    if i < 0 or not body[i + 3:].startswith(MARKERS):
        return None
    return body[:i] + '<p>' + esc(line) + '</p>'

bot = env['res.partner'].sudo().search([('name', '=', ${py("UTAK بوت")})], limit=1)
updated = 0
for rec in records:
    mid = rec.x_echo_message_id
    if not mid or not bot:
        continue
    msg = env['mail.message'].sudo().browse(mid).exists()
    if not msg or msg.model != 'discuss.channel' or msg.author_id != bot or msg.message_type != 'comment':
        continue
    if not env['discuss.channel'].sudo().browse(msg.res_id).x_wa_partner_id:
        continue
    at = ''
    if rec.x_processed_at:
        at = (rec.x_processed_at + datetime.timedelta(hours=3)).strftime('%H:%M')
    line = status_line(rec.x_status or '', at, rec.x_meta_error or '')
    if not line:
        continue
    body = new_body(str(msg.body or ''), line)
    if body is None:
        continue
    if body != str(msg.body or ''):
        msg.write({'body': body})
    updated += 1
action = {'type': 'ir.actions.act_window_close', 'infos': {'utak_updated': updated}}
`;
}

// ------------------------------------------------------------------ what the recipient reads

export interface TemplateText {
  id: number;
  name: string;
  /** Header (text), body and footer as Meta approved them, {{n}} unfilled. */
  bodyText: string;
  /** Button labels, one per line. */
  buttonsText: string;
}

const TEXT_TTL_MS = 10 * 60 * 1000;
const textCache = new Map<string, { t: TemplateText | null; at: number }>();
/** Test hook. */
export function clearTemplateTextCache(): void { textCache.clear(); }

/** The approved text of template `name` from its x_whatsapp_template row (10-minute cache). */
export async function templateText(env: Env, name: string, language = "ar"): Promise<TemplateText | null> {
  const key = `${name}::${language}`;
  const hit = textCache.get(key);
  if (hit && Date.now() - hit.at < TEXT_TTL_MS) return hit.t;
  try {
    const { call } = await import("./odoo");
    const rows = await call<Array<{ id: number; x_meta_template_id: string; x_language: string | false; x_body_text: string | false; x_buttons_text: string | false }>>(
      env, "x_whatsapp_template", "search_read", {
        domain: [["x_meta_template_id", "=", name]],
        fields: ["id", "x_meta_template_id", "x_language", "x_body_text", "x_buttons_text"],
        limit: 5,
      });
    const row = rows.find((r) => String(r.x_language || "").toLowerCase() === language.toLowerCase()) ?? rows[0];
    const t = row ? { id: row.id, name, bodyText: String(row.x_body_text || ""), buttonsText: String(row.x_buttons_text || "") } : null;
    if (t) textCache.set(key, { t, at: Date.now() });
    return t;
  } catch (e) {
    console.warn(`[record] template text ${name} unreadable`, (e as Error)?.message);
    return null;
  }
}

type TemplateBody = {
  template?: {
    name?: string;
    language?: { code?: string };
    components?: Array<{ type?: string; parameters?: Array<{ type?: string; text?: string; document?: { filename?: string }; image?: unknown; video?: unknown }> }>;
  };
};

/** {{1}}, {{2}}, … of a template body as sent. */
export function templateParams(body: Record<string, unknown>): string[] {
  const comps = (body as TemplateBody).template?.components ?? [];
  return comps.filter((c) => c?.type === "body").flatMap((c) => c.parameters ?? []).map((p) => String(p?.text ?? ""));
}

function headerLine(body: Record<string, unknown>): string {
  const comps = (body as TemplateBody).template?.components ?? [];
  const p = comps.find((c) => c?.type === "header")?.parameters?.[0];
  if (!p) return "";
  if (p.type === "document") return `📎 ${p.document?.filename ?? "مستند"}`;
  if (p.type === "image") return "🖼️ صورة";
  if (p.type === "video") return "🎬 فيديو";
  return "";
}

/**
 * A template message as its recipient reads it: the approved text with the
 * variables filled in, a media header as one line, the buttons as «🔘 label».
 * Without the approved text: the filled variables under UNSYNCED_LINE.
 */
export function renderTemplateMessage(t: TemplateText | null, body: Record<string, unknown>): { text: string; synced: boolean } {
  const params = templateParams(body);
  const head = headerLine(body);
  if (!t || !t.bodyText.trim()) {
    const lines = [head, UNSYNCED_LINE, ...params.filter((p) => p !== "").map((p) => `• ${p}`)].filter(Boolean);
    return { text: lines.join("\n"), synced: false };
  }
  const filled = t.bodyText.replace(/\{\{(\d+)\}\}/g, (m, n) => params[Number(n) - 1] ?? m);
  const buttons = t.buttonsText.split("\n").map((l) => l.trim()).filter(Boolean).map((l) => `🔘 ${l}`);
  return { text: [head, filled.trim(), ...buttons].filter(Boolean).join("\n"), synced: true };
}

/** A session (non-template) message as its recipient reads it. */
export function sessionText(body: Record<string, unknown>): string {
  const b = body as {
    type?: string;
    text?: { body?: string };
    location?: { latitude?: number; longitude?: number; name?: string; address?: string };
    interactive?: { body?: { text?: string }; action?: { buttons?: Array<{ reply?: { title?: string } }> } };
    document?: { filename?: string };
    template?: unknown;
  };
  if (b.type === "text") return String(b.text?.body ?? "");
  if (b.type === "location") {
    const label = b.location?.name ?? b.location?.address ?? "";
    return `📍 موقع${label ? " · " + label : ""} — https://maps.google.com/?q=${b.location?.latitude},${b.location?.longitude}`;
  }
  if (b.type === "interactive") {
    const text = b.interactive?.body?.text ?? "";
    const btns = (b.interactive?.action?.buttons ?? []).map((btn) => btn?.reply?.title ?? "").filter(Boolean).map((t) => `🔘 ${t}`);
    return [text, ...btns].filter(Boolean).join("\n");
  }
  if (b.type === "document") return `📎 ${b.document?.filename ?? "مستند"}`;
  if (b.type === "template") return renderTemplateMessage(null, body).text;
  return `[${b.type ?? "unknown"}]`;
}

export interface Shown {
  text: string;
  kind: "text" | "template" | "document";
  templateId?: number;
  templateName?: string;
  params?: string[];
  synced: boolean;
}

/** What the recipient reads, for any body the gateway sends (templates read their text from Odoo). */
export async function outboundText(env: Env, body: Record<string, unknown>): Promise<Shown> {
  const type = String((body as { type?: string }).type ?? "");
  if (type !== "template") {
    return { text: sessionText(body), kind: type === "document" ? "document" : "text", synced: true };
  }
  const tb = body as TemplateBody;
  const name = String(tb.template?.name ?? "");
  const t = name ? await templateText(env, name, tb.template?.language?.code || "ar") : null;
  const r = renderTemplateMessage(t, body);
  return { text: r.text, kind: "template", templateId: t?.id, templateName: name || undefined, params: templateParams(body), synced: r.synced };
}

