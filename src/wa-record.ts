// Every outbound WhatsApp message on record — 2026-09-25 (STATUS § 36).
//
// A message the gateway (src/wa-gateway.ts) hands to Meta — or holds — gets,
// from here:
//   1. an x_wa_message row, written before the send returns, on the number's
//      partner (Baraa's number too: his channel is «واتساب · … · +966…4962»).
//      Its text (x_body) is the message exactly as the recipient reads it: a
//      template is rendered from its approved text in Odoo (x_body_text /
//      x_buttons_text, filled by the template sync) with the variables filled
//      in and one «🔘 label» line per button. The template's name stays in
//      technical fields (x_template_id, x_params, x_debug_payload) and never
//      reaches Discuss. A template whose text is not synced shows its filled
//      variables under «⚠️ نص القالب غير متزامن» — never the name alone.
//   2. a line in the number's Discuss channel, in § 28's style (the «🤖 آلي»
//      box). A held message shows its full text with a status line «⏳ محفوظة…»
//      under it; when it goes, expires, is dropped or refused, that same line
//      changes (server action «UTAK — سطر حالة رسالة واتساب», run as the row:
//      it edits only a bot line of a WhatsApp channel that this row points to,
//      and only its last paragraph when that is a status line). When Odoo does
//      not edit it, a short reply under the message says the same.
// The Discuss line never holds up the send or the row. A line that could not
// be posted leaves the row x_echo_status «pending»; the */5 tick retries it
// three times, then marks the row «failed». A row Odoo refused to create is
// kept in KV and retried the same way (the D1 log keeps every send anyway).

