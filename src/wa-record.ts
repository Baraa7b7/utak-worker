export interface EchoOpts {
  template?: boolean;
  manual?: boolean;
  backfilled?: boolean;
  /** A status paragraph under the box (held, and a held message's later fate). */
  status?: string;
}

/** The § 28 box (theme-inherited, «🤖 آلي» / «📤 يدوي»), with an optional status line under it. */
export function echoHtml(text: string, o: EchoOpts = {}): string {
  const tags = [o.manual ? "📤 يدوي" : "🤖 آلي", o.template ? "قالب" : "", o.backfilled ? BACKFILL_TAG : ""].filter(Boolean).join(" · ");
  const body = escapeHtml(text).replace(/\n/g, "<br/>");
  // AUTO_STYLE, as in src/wa-inbox.ts (kept literal here: no static import cycle)
  const box = `<p style="border-right-style:solid; border-right-width:3px; padding-right:8px; margin:0"><strong>${tags}</strong><br/>${body}</p>`;
  return o.status ? `${box}<p>${escapeHtml(o.status)}</p>` : box;
}

/** The partner whose channel shows this number — Baraa's included (§ 36). */
export async function partnerForNumber(env: Env, to: string): Promise<{ id: number; name: string } | null> {
  const digits = waDigits(to);
  if (!digits) return null;
  try {
    const { inboxPartnerForNumber } = await import("./wa-inbox");
    const byChannel = await inboxPartnerForNumber(env, digits);
    if (byChannel) return byChannel;
    const { call } = await import("./odoo");
    const rows = await call<Array<{ id: number; name: string }>>(env, "res.partner", "search_read", {
      domain: ["|", ["x_whatsapp_number", "ilike", digits], ["phone", "ilike", digits]],
      fields: ["id", "name"],
      limit: 1,
    });
    return rows[0] ?? null;
  } catch {
    return null;
  }
}

/** The id message_post answered with: a number, [id], or {id} (JSON-2 serialises the record). */
function msgId(v: unknown): number | null {
  const n = Array.isArray(v) ? v[0] : v && typeof v === "object" ? (v as { id?: unknown }).id : v;
  return typeof n === "number" && n > 0 ? n : null;
}

/** Post `html` in the partner's channel as «UTAK بوت». Returns the message id, or null. */
async function postEcho(
  env: Env,
  partner: { id: number; name: string },
  number: string,
  html: string,
  extra: Record<string, unknown> = {},
): Promise<number | null> {
  const { ensureInboxChannel, getBotPartnerId, stripFixedColors } = await import("./wa-inbox");
  const channelId = await ensureInboxChannel(env, partner.id, partner.name, { number });
  if (!channelId) throw new Error("no channel");
  const bot = await getBotPartnerId(env);
  if (!bot) throw new Error("UTAK بوت partner missing");
  const { call } = await import("./odoo");
  const res = await call<unknown>(env, "discuss.channel", "message_post", {
    ids: [channelId],
    body: stripFixedColors(html),
    body_is_html: true,
    message_type: "comment",
    author_id: bot,
    subtype_xmlid: "mail.mt_comment",
    ...extra,
  });
  return msgId(res) ?? 0;
}

const ACTION_KEY = "wa_rec:v1:line_action_id";
async function lineActionId(env: Env): Promise<number | null> {
  try {
    const cached = await env.MSG_DEDUP.get(ACTION_KEY);
    if (cached) return Number(cached) || null;
  } catch { /* ignore */ }
  try {
    const { call } = await import("./odoo");
    const rows = await call<Array<{ id: number }>>(env, "ir.actions.server", "search_read", {
      domain: [["name", "=", HELD_LINE_ACTION_NAME]], fields: ["id"], limit: 1,
    });
    const id = rows[0]?.id ?? null;
    if (id) { try { await env.MSG_DEDUP.put(ACTION_KEY, String(id), { expirationTtl: 3600 }); } catch { /* ignore */ } }
    return id;
  } catch {
    return null;
  }
}

/** Run the server action on row `rowId`: true when it edited the line. */
async function editStatusLine(env: Env, rowId: number): Promise<boolean> {
  const actionId = await lineActionId(env);
  if (!actionId) return false;
  try {
    const { call } = await import("./odoo");
    const res = await call<{ infos?: { utak_updated?: number } } | null>(env, "ir.actions.server", "run", {
      ids: [actionId],
      context: { active_model: "x_wa_message", active_id: rowId, active_ids: [rowId] },
    });
    return Number(res?.infos?.utak_updated ?? 0) > 0;
  } catch (e) {
    console.warn(`[record] status line edit row=${rowId} refused`, (e as Error)?.message);
    return false;
  }
}

