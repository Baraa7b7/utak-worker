export const ROW_FIELDS = [
  "id", "x_partner_id", "x_body", "x_kind", "x_status", "x_source", "x_manual", "x_processed_at", "x_meta_error",
  "x_debug_payload", "x_echo_status", "x_echo_message_id", "x_backfilled", "x_meta_message_id",
];

export interface RowView {
  id: number;
  x_partner_id: [number, string] | false;
  x_body: string | false;
  x_kind: string | false;
  x_status: string | false;
  x_source: string | false;
  x_manual?: boolean;
  x_processed_at: string | false;
  x_meta_error: string | false;
  x_debug_payload: string | false;
  x_echo_status: string | false;
  x_echo_message_id: number | false;
  x_backfilled?: boolean;
}

const SENT_LIKE = new Set(["sent", "delivered", "read"]);
const nowOdoo = (ms: number = Date.now()) => new Date(ms).toISOString().replace("T", " ").slice(0, 19);

function heldUntilOf(row: RowView): string {
  try {
    const p = JSON.parse(String(row.x_debug_payload || "{}"));
    const ms = Date.parse(p.expiresAt);
    if (Number.isFinite(ms)) return riyadhLabel(ms);
  } catch { /* ignore */ }
  return "نهاية اليوم";
}

export function riyadhLabel(ms: number): string {
  const d = new Date(ms);
  const m = riyadhMinutes(d);
  return `${arabicDate(riyadhDateKey(d))}، ${String(Math.floor(m / 60)).padStart(2, "0")}:${String(m % 60).padStart(2, "0")}`;
}

/**
 * The row's Discuss line, whatever its state: a held line posted when there is
 * none, a status line edited (or a reply) when the message changed fate, the
 * full echo for a message that went. Throws when the line could not be posted.
 * Returns the message id it wrote on the row, or null when nothing applies.
 */
export async function echoForRow(env: Env, row: RowView, numberHint?: string): Promise<number | null> {
  const partner = row.x_partner_id ? { id: row.x_partner_id[0], name: row.x_partner_id[1] } : null;
  if (!partner) {
    await writeRow(env, row.id, { x_echo_status: "none" });
    return null;
  }
  const status = String(row.x_status || "");
  const text = String(row.x_body || "");
  const at = riyadhHHMM(row.x_processed_at);
  const opts: EchoOpts = { template: row.x_kind === "template", manual: row.x_source === "manual" || row.x_manual === true, backfilled: row.x_backfilled === true };
  const number = numberHint ?? "";
  if (row.x_echo_message_id) {
    // a held line exists: its status changes, or a reply says so
    const line = statusLineFor(status, at, String(row.x_meta_error || ""));
    if (line && !(await editStatusLine(env, row.id))) {
      const { ensureInboxChannel } = await import("./wa-inbox");
      if (!(await ensureInboxChannel(env, partner.id, partner.name, { number }))) throw new Error("no channel");
      await postEcho(env, partner, number, `<p>${escapeHtml(line)}</p>`, { parent_id: row.x_echo_message_id });
    }
    await writeRow(env, row.id, { x_echo_status: "posted" });
    return row.x_echo_message_id;
  }
  if (!text) {
    await writeRow(env, row.id, { x_echo_status: "none" });
    return null;
  }
  let html: string;
  if (status === "held") html = echoHtml(text, { ...opts, status: heldLine(heldUntilOf(row)) });
  else if (SENT_LIKE.has(status)) html = echoHtml(text, opts);
  else html = echoHtml(text, { ...opts, status: statusLineFor(status, at, String(row.x_meta_error || "")) });
  const id = await postEcho(env, partner, number, html);
  await writeRow(env, row.id, { x_echo_status: "posted", ...(id ? { x_echo_message_id: id } : {}) });
  return id;
}

async function writeRow(env: Env, id: number, vals: Record<string, unknown>): Promise<void> {
  const { call } = await import("./odoo");
  await call(env, "x_wa_message", "write", { ids: [id], vals });
}

async function readRow(env: Env, id: number): Promise<RowView | null> {
  const { call } = await import("./odoo");
  const rows = await call<RowView[]>(env, "x_wa_message", "read", { ids: [id], fields: ROW_FIELDS });
  return rows[0] ?? null;
}

/** The row's line now (awaited, or in ctx.waitUntil). A failure leaves «pending» for the every-5-minutes retry. */
export async function echoRowSoon(env: Env, rowId: number | undefined, number: string, ctx?: ExecutionContext): Promise<void> {
  if (!rowId) return;
  const task = (async () => {
    try {
      const row = await readRow(env, rowId);
      if (row) await echoForRow(env, row, number);
    } catch (e) {
      console.warn(`[record] Discuss line row=${rowId} to=${maskPhone(number)} failed — retried by the */5 tick`, (e as Error)?.message);
    }
  })();
  if (ctx) ctx.waitUntil(task);
  else await task;
}

